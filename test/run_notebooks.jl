function run_one_notebook_inplace(
    nb::String,
    demos_dir::AbstractString,
    kernel::AbstractString,
    timeout::Int,
)
    print("Executing ", nb, " with kernel ", kernel, " ... ")
    notebook_path = joinpath(demos_dir, nb)
    captured = ""
    failed = false
    err_text = ""
    elapsed = @elapsed try
        mktempdir() do ipython_dir
            mktemp() do _, io
                cmd = Cmd([
                    notebook_jupyter(),
                    "nbconvert",
                    "--to",
                    "notebook",
                    "--execute",
                    "--inplace",
                    "--ExecutePreprocessor.kernel_name=$(kernel)",
                    "--ExecutePreprocessor.timeout=$(timeout)",
                    basename(notebook_path),
                ],)
                cmd = Cmd(cmd; dir=dirname(notebook_path))
                proc = run(
                    pipeline(
                        ignorestatus(addenv(cmd, "IPYTHONDIR" => ipython_dir)),
                        stdout=io,
                        stderr=io,
                    ),
                )
                flush(io)
                seekstart(io)
                captured = read(io, String)
                success(proc) || error("nbconvert exited with code $(proc.exitcode)")
            end
        end
    catch e
        failed = true
        err_text = sprint(io -> showerror(io, e, catch_backtrace()))
    end

    if failed
        println("FAILED")
        if !isempty(strip(captured))
            println("---- captured nbconvert output ----")
            print(captured)
            endswith(captured, '\n') || println()
            println("---- end captured nbconvert output ----")
        end
        println("  x FAILED: ", err_text)
        println("  time: ", fmt_duration(elapsed))
        return false, elapsed, 0
    end

    println("ok [$(fmt_duration(elapsed))]")
    return true, elapsed, 0
end

function run_one_notebook(
    nb::String,
    demos_dir::AbstractString,
    clogger::CountingLogger,
    verbose::Bool,
    timeout::Int,
)
    print("Running ", nb, " ... ")
    # Execute the notebook in a *child process* and enforce the timeout by
    # killing that process. The previous in-process approach used
    # `Threads.@spawn` + `schedule(task, InterruptException())`, which cannot
    # interrupt a task blocked inside a native `ccall` (e.g. the qmctoolscl C
    # library that backs `gen_samples`). When such a call ran long, the soft
    # timeout never fired and CI hung until the GitHub step timeout cancelled
    # the whole job. Killing the process always works.
    cmd = addenv(
        Cmd(vcat(collect(Base.julia_cmd()), [joinpath(@__DIR__, "run_notebooks.jl")])),
        "JULIA_PROJECT" => current_project_dir(),
        "JULIA_NUM_THREADS" => string(Threads.nthreads()),
        "QUASIMC_SKIP_PKG_SETUP" => "1",
        "QUASIMC_NB_ONE" => nb,
        "QUASIMC_NOTEBOOK_VERBOSE" => verbose ? "1" : "0",
    )
    buf = IOBuffer()
    proc = run(pipeline(ignorestatus(cmd); stdout=buf, stderr=buf); wait=false)
    failed = false
    err_text = ""
    elapsed = @elapsed begin
        if timedwait(() -> process_exited(proc), float(timeout); pollint=1.0) == :timed_out
            kill(proc)                                   # SIGTERM
            if timedwait(() -> process_exited(proc), 10.0; pollint=0.5) == :timed_out
                kill(proc, 9)                            # SIGKILL
            end
            wait(proc)
            failed = true
            err_text = "timed out after $(fmt_duration(timeout)) (process killed)"
        else
            failed = !success(proc)
            failed && (err_text = "notebook process exited with code $(proc.exitcode)")
        end
    end

    # The child appends a machine-readable result line; parse and strip it so
    # warning counts still feed the run summary.
    warnings = 0
    kept = String[]
    for ln in split(String(take!(buf)), '\n')
        m = match(r"^##(?:QUASIMC|QMC)_NB_RESULT ok=(\w+) warnings=(\d+)$", ln)
        if m === nothing
            push!(kept, ln)
        else
            m.captures[1] == "false" && (failed = true)
            warnings = parse(Int, m.captures[2])
        end
    end
    captured = join(kept, '\n')

    if failed
        println("FAILED")
        if !isempty(strip(captured))
            println("---- captured notebook output ----")
            print(captured)
            endswith(captured, '\n') || println()
            println("---- end captured output ----")
        end
        isempty(err_text) && (err_text = "notebook failed")
        println("  x FAILED: ", err_text)
        println("  time: ", fmt_duration(elapsed))
        println("$(NB_TIMING_TAG)\t$(nb)\t$(round(elapsed; digits=3))")
        return false, elapsed, warnings
    end

    wtxt = warnings > 0 ? ", $warnings warning(s)" : ""
    println("ok [$(fmt_duration(elapsed))]$wtxt")
    # Machine-readable timing consumed by run_parallel to build the LPT timing cache.
    println("$(NB_TIMING_TAG)\t$(nb)\t$(round(elapsed; digits=3))")
    return true, elapsed, warnings
end

function run_serial(notebooks::Vector{String}, demos_dir::AbstractString, opts::NotebookOptions)
    times = Dict{String, Float64}()
    warnings_by_notebook = Dict{String, Int}()
    errors = String[]
    clogger = CountingLogger()
    verbose = getenv_compat("QUASIMC_NOTEBOOK_VERBOSE", "QMC_NOTEBOOK_VERBOSE", "0") == "1"

    for nb in notebooks
        ok, elapsed, warnings =
            opts.overwrite ?
            run_one_notebook_inplace(nb, demos_dir, opts.kernel, opts.timeout) :
            run_one_notebook(nb, demos_dir, clogger, verbose, opts.timeout)
        times[nb] = elapsed
        warnings_by_notebook[nb] = warnings
        ok || push!(errors, nb)
        GC.gc()
    end

    total_warnings = sum(values(warnings_by_notebook); init=0)
    total_time = sum(values(times); init=0.0)
    n_pass = length(notebooks) - length(errors)

    println("\n", "="^60)
    println("Summary")
    println("="^60)
    for nb in errors
        w = get(warnings_by_notebook, nb, 0)
        t = get(times, nb, 0.0)
        wtxt = w > 0 ? ", $w warning(s)" : ""
        println("  x FAILED  $nb  [$(fmt_duration(t))]$wtxt")
    end
    println("-"^60)
    println(
        "Ran $(length(notebooks)) notebook(s): $(n_pass) passed, $(length(errors)) failed, " *
        "$(total_warnings) warning(s) in $(fmt_duration(total_time)).",
    )

    if !isempty(errors)
        exit(1)
    else
        println("All notebooks passed.")
    end
end

function run_parallel(notebooks::Vector{String}, opts::NotebookOptions)
    times = load_notebook_times()
    shard_notebooks = if !isempty(times)
        coverage = count(nb -> haskey(times, nb), notebooks)
        println(
            "LPT scheduling: $(coverage)/$(length(notebooks)) notebook(s) have timing data.",
        )
        split_work_lpt(notebooks, opts.jobs, times)
    else
        split_work(notebooks, opts.jobs)
    end
    println(
        "Running $(length(notebooks)) notebook(s) across $(length(shard_notebooks)) " *
        "parallel shard(s)...",
    )
    wall = @elapsed begin
        shards = [
            start_child_shard(shard, idx, length(shard_notebooks), opts) for
            (idx, shard) in enumerate(shard_notebooks)
        ]
        while any(!istaskdone(shard.task) for shard in shards)
            for shard in shards
                drain_shard_output!(shard)
                maybe_print_shard_heartbeat!(shard)
            end
            sleep(1)
        end
        results = map(fetch, getfield.(shards, :task))
        # Collect per-notebook timings from shard logs before cleanup, then
        # persist them so the next run can use LPT scheduling.
        all_times = load_notebook_times()
        failed = false
        for (shard, result) in zip(shards, results)
            drain_shard_output!(shard)
            failed |= !result.ok
            try
                for line in eachline(result.log_path)
                    parts = split(line, '\t')
                    if length(parts) == 3 &&
                       (parts[1] == NB_TIMING_TAG || parts[1] == NB_TIMING_TAG_LEGACY)
                        all_times[String(parts[2])] = parse(Float64, parts[3])
                    end
                end
            catch
            end
            rm(result.log_path; force=true)
        end
        save_notebook_times(all_times)
        println()
        println("Parallel shard summary")
        println("-"^60)
        for result in results
            status = result.ok ? "passed" : "FAILED"
            println(
                "  shard $(result.idx)/$(result.count): $status " *
                "($(length(result.notebooks)) notebook(s), $(fmt_duration(result.elapsed)))",
            )
        end
        if failed
            println("-"^60)
            println("One or more notebook shards failed; see shard logs above.")
            exit(1)
        end
    end
    println()
    println(
        "Completed parallel notebook run for $(length(notebooks)) notebook(s) in " *
        "$(fmt_duration(wall)).",
    )
end

function collect_notebooks(demos_dir::AbstractString)
    notebooks = String[]
    for (root, _, files) in walkdir(demos_dir)
        rel_root = relpath(root, demos_dir)
        path_parts =
            rel_root == "." ? String[] : split(rel_root, Base.Filesystem.path_separator)
        any(startswith(part, ".") for part in path_parts) && continue
        for file in files
            endswith(file, ".ipynb") || continue
            startswith(file, ".") && continue
            endswith(file, "-checkpoint.ipynb") && continue
            push!(notebooks, relpath(joinpath(root, file), demos_dir))
        end
    end
    return sort(notebooks)
end

demos_dir = joinpath(@__DIR__, "..", "demos")

# Child mode: execute exactly one notebook in-process and exit. The parent
# (`run_one_notebook`) launches this with QUASIMC_NB_ONE set and enforces the
# per-notebook timeout by killing the process — the only reliable way to stop a
# notebook stuck inside a native `ccall` (e.g. qmctoolscl).
if haskey(ENV, "QUASIMC_NB_ONE") || haskey(ENV, "QMC_NB_ONE")
    # `let` keeps these names local so the `one_ok` assignment in the `catch`
    # below is unambiguous; at global scope it would trip a soft-scope warning.
    let one_nb = getenv_compat("QUASIMC_NB_ONE", "QMC_NB_ONE"),
        one_clog = CountingLogger(),
        one_ok = true

        one_clog.current_nb[] = one_nb
        try
            with_suppressed_display() do
                with_logger(one_clog) do
                    @nbinclude(joinpath(demos_dir, one_nb))
                end
            end
        catch e
            one_ok = false
            showerror(stderr, e, catch_backtrace())
            println(stderr)
        end
        flush(stdout)
        flush(stderr)
        println("$(NB_RESULT_TAG) ok=$(one_ok) warnings=$(get(one_clog.counts, one_nb, 0))")
        exit(one_ok ? 0 : 1)
    end
end

all_notebooks = collect_notebooks(demos_dir)
opts, selectors = parse_args(ARGS)
notebooks = select_shard(select_notebooks(all_notebooks, selectors), opts)

if opts.jobs == 1 || length(notebooks) <= 1
    run_serial(notebooks, demos_dir, opts)
else
    run_parallel(notebooks, opts)
end
