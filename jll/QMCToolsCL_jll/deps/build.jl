const QMCTOOLSCL_VERSION = "1.2.3"

pkgdir = normpath(joinpath(@__DIR__, ".."))
vendor_dir = joinpath(pkgdir, "vendor", "windows")
source_root = joinpath(pkgdir, "upstream", "qmctoolscl-1.2.3", "qmctoolscl", "c_funcs")
usr_lib_dir = joinpath(@__DIR__, "usr", "lib")
mkpath(usr_lib_dir)

function write_statefile(libpath::AbstractString)
    statefile = joinpath(@__DIR__, "build_state.txt")
    open(statefile, "w") do io
        println(io, "# Generated by QMCToolsCL_jll/deps/build.jl")
        println(io, "libqmctoolscl=", libpath)
        println(io, "qmctoolscl_version=", QMCTOOLSCL_VERSION)
    end
    legacy_depsfile = joinpath(@__DIR__, "deps.jl")
    isfile(legacy_depsfile) && rm(legacy_depsfile; force=true)
end

function unix_compiler()
    for candidate in ("cc", "clang", "gcc")
        exe = Sys.which(candidate)
        exe === nothing || return exe
    end
    error(
        "No C compiler found for QMCToolsCL_jll. " *
        "Tried cc, clang, and gcc on PATH.",
    )
end

function unix_library_name()
    return Sys.isapple() ? "libqmctoolscl.dylib" : "libqmctoolscl.so"
end

function unix_linker_flag()
    return Sys.isapple() ? "-dynamiclib" : "-shared"
end

function source_files()
    files = readdir(source_root; join=true)
    c_files = filter(path -> endswith(path, ".c"), files)
    return sort(filter(path -> basename(path) != "python_compat.c", c_files))
end

function build_unix_library()
    compiler = unix_compiler()
    output = joinpath(usr_lib_dir, unix_library_name())
    sources = source_files()
    # -march=native: emit instructions for the host CPU (enables AVX2/AVX-512
    #   autovectorisation where available). The resulting library is not portable
    #   to other machines, which is fine for a locally staged jll.
    # -ffast-math: permits the compiler to reorder and approximate floating-point
    #   operations (non-associative transforms, no-NaN/Inf assumptions). The
    #   qmctoolscl kernels are dominated by integer Gray-code arithmetic and
    #   bit-level float reconstruction, so in practice this flag is safe here,
    #   but it must be revisited if future kernel versions add numerically
    #   sensitive float reductions.
    # -flto: link-time optimisation across all 28 translation units. Allows the
    #   linker to inline cross-file calls and eliminate dead code, which is
    #   significant when hot-path functions (Gray-code generators) call helpers
    #   defined in separate .c files.
    # -funroll-loops: unroll inner loops over dimension d (typically 1–16) and
    #   replications, eliminating loop-counter overhead on short iterations.
    cmd = Cmd(
        [
            compiler,
            unix_linker_flag(),
            "-O3",
            "-march=native",
            "-ffast-math",
            "-flto",
            "-funroll-loops",
            "-fPIC",
            "-std=c99",
            "-I",
            source_root,
            "-o",
            output,
            sources...,
            "-lm",
        ],
    )
    run(cmd)
    return output
end

function windows_compiler()
    # GitHub Actions windows-latest ships MSYS2 MinGW64 at a known path; check
    # those first so the build works without PATH manipulation in the workflow.
    explicit = [
        "C:\\msys64\\mingw64\\bin\\gcc.exe",
        "C:\\msys64\\usr\\bin\\gcc.exe",
        "C:\\mingw64\\bin\\gcc.exe",
    ]
    for p in explicit
        isfile(p) && return p
    end
    # Fall back to whatever the shell PATH offers.
    for candidate in ("gcc", "cc", "clang")
        p = Sys.which(candidate)
        p === nothing || return p
    end
    return nothing
end

function build_windows_library()
    compiler = windows_compiler()
    if compiler === nothing
        # No compiler found — try the pre-built vendored binary.
        src = joinpath(vendor_dir, "c_lib.cp312-win_amd64.pyd")
        isfile(src) || error(
            "No Windows C compiler (gcc/clang) found and no vendored binary " *
            "at $(repr(src)).\n" *
            "Install MinGW (e.g. via MSYS2) so gcc is reachable, or provide " *
            "the pre-built library.",
        )
        dst = joinpath(usr_lib_dir, "c_lib.cp312-win_amd64.pyd")
        cp(src, dst; force=true)
        return dst
    end
    output = joinpath(usr_lib_dir, "libqmctoolscl.dll")
    sources = source_files()
    # -O2 / -ffast-math: optimise without the LTO/march flags that can be
    #   fragile on some MinGW versions shipped with MSYS2.
    # -Wl,--export-all-symbols: make every non-static C symbol visible so that
    #   Julia's Libdl.dlsym can resolve function names without a .def file.
    cmd = Cmd([
        compiler,
        "-shared",
        "-O2",
        "-ffast-math",
        "-funroll-loops",
        "-std=c99",
        "-I", source_root,
        "-o", output,
        sources...,
        "-lm",
        "-Wl,--export-all-symbols",
    ])
    run(cmd)
    return output
end

libpath = Sys.iswindows() ? build_windows_library() : build_unix_library()
write_statefile(libpath)
