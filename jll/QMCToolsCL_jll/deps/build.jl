const QMCTOOLSCL_VERSION = "1.2.3"

pkgdir = normpath(joinpath(@__DIR__, ".."))
vendor_dir = joinpath(pkgdir, "vendor", "windows")
source_root = joinpath(pkgdir, "upstream", "qmctoolscl-1.2.3", "qmctoolscl", "c_funcs")
usr_lib_dir = joinpath(@__DIR__, "usr", "lib")
mkpath(usr_lib_dir)

function write_statefile(libpath::AbstractString)
    statefile = joinpath(@__DIR__, "build_state.txt")
    open(statefile, "w") do io
        println(io, "# Generated by QMCToolsCL_jll/deps/build.jl")
        println(io, "libqmctoolscl=", libpath)
        println(io, "qmctoolscl_version=", QMCTOOLSCL_VERSION)
    end
    legacy_depsfile = joinpath(@__DIR__, "deps.jl")
    isfile(legacy_depsfile) && rm(legacy_depsfile; force=true)
end

function unix_compiler()
    for candidate in ("cc", "clang", "gcc")
        exe = Sys.which(candidate)
        exe === nothing || return exe
    end
    error(
        "No C compiler found for QMCToolsCL_jll. " *
        "Tried cc, clang, and gcc on PATH.",
    )
end

function unix_library_name()
    return Sys.isapple() ? "libqmctoolscl.dylib" : "libqmctoolscl.so"
end

function unix_linker_flag()
    return Sys.isapple() ? "-dynamiclib" : "-shared"
end

function source_files()
    files = readdir(source_root; join=true)
    c_files = filter(path -> endswith(path, ".c"), files)
    return sort(filter(path -> basename(path) != "python_compat.c", c_files))
end

function build_unix_library()
    compiler = unix_compiler()
    output = joinpath(usr_lib_dir, unix_library_name())
    sources = source_files()
    cmd = Cmd(
        [
            compiler,
            unix_linker_flag(),
            "-O3",
            "-fPIC",
            "-std=c99",
            "-I",
            source_root,
            "-o",
            output,
            sources...,
            "-lm",
        ],
    )
    run(cmd)
    return output
end

function install_windows_library()
    src = joinpath(vendor_dir, "c_lib.cp312-win_amd64.pyd")
    isfile(src) || error("Missing vendored Windows QMCToolsCL binary at $(repr(src)).")
    dst = joinpath(usr_lib_dir, "c_lib.cp312-win_amd64.pyd")
    cp(src, dst; force=true)
    return dst
end

libpath = Sys.iswindows() ? install_windows_library() : build_unix_library()
write_statefile(libpath)
